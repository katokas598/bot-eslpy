const { MessageEmbed } = require('discord.js');

module.exports = {
    name: 'help',
    description: 'Показать список команд',
    async execute(message, args, client, db) {
        const embed = new MessageEmbed()
            .setColor('#3498db')
            .setTitle('📚 Список команд')
            .setDescription(`
**🎵 Музыка**
\`!play <ссылка>\` - Воспроизвести музыку
\`!stop\` - Остановить музыку

**🛡 Модерация**
\`!ban <пользователь> [причина]\` - Забанить
\`!kick <пользователь> [причина]\` - Кикнуть
\`!mute <пользователь> <время> [причина]\` - Замутить
\`!warn <пользователь> [причина]\` - Предупреждение
\`!clear <число>\` - Очистить сообщения

**📊 Уровни и XP**
\`!level\` - Ваш уровень
\`!leaderboard\` - Топ игроков (все время)
\`!weektop\` - Топ за неделю
\`!monthtop\` - Топ за месяц
\`!levelroles\` - Роли за уровни

**🎁 Награды**
\`!daily\` - Ежедневная награда
\`!streak\` - Серия активности
\`!rewards\` - Достижения и награды

**🎫 Тикеты**
\`!ticket [причина]\` - Создать тикет

**🎲 Утилиты**
\`!ping\` - Пинг бота
\`!random <число>\` - Случайное число
\`!calc <выражение>\` - Калькулятор
\`!translate <язык> <текст>\` - Перевод
\`!weather <город>\` - Погода
\`!embed <заголовок> | <текст>\` - Создать embed

**ℹ️ Информация**
\`!user [пользователь]\` - Информация о пользователе
\`!server\` - Информация о сервере
\`!stats\` - Статистика сервера
            `)
            .setTimestamp()
            .setFooter({ text: `Prefix: ${client.prefix}` });

        message.reply({ embeds: [embed] });
    }
};